/* ---------------------------------------------------------------
   Rendu d'un portrait décalqué.
   --------------------------------------------------------------- */
var PORTRAITS = {
  meuf:{ poly:PORTRAIT_MEUF_POLY, coul:PORTRAIT_MEUF_COULEURS, h:PORTRAIT_MEUF_H, pret:null },
  mec :{ poly:PORTRAIT_MEC_POLY,  coul:PORTRAIT_MEC_COULEURS,  h:PORTRAIT_MEC_H,  pret:null }
};
function preparePortrait(p){
  if(p.pret) return;
  var t = {}, i;
  for(i = 0; i < VT_ALPHABET.length; i++) t[VT_ALPHABET.charAt(i)] = i;
  p.pret = [];
  for(i = 0; i < p.poly.length; i++){
    var s = p.poly[i], q = [];
    for(var k = 0; k < s.length; k += 4){
      q.push((t[s.charAt(k)] * VT_BASE + t[s.charAt(k + 1)] - 40) / 20);
      q.push((t[s.charAt(k + 2)] * VT_BASE + t[s.charAt(k + 3)] - 40) / 20);
    }
    p.pret.push(q);
  }
}
function dessinePortrait(c, cle, x, y, larg){
  var p = PORTRAITS[cle];
  if(!p) return;
  preparePortrait(p);
  var k = larg / 100;
  c.save();
  c.translate(x, y);
  c.scale(k, k);
  for(var i = 0; i < p.pret.length; i++){
    c.fillStyle = p.coul[i];
    vtTrace(c, p.pret[i]);
    c.fill();
    c.strokeStyle = p.coul[i];
    c.lineWidth = 0.22; c.lineJoin = "round";
    c.stroke();
  }
  c.restore();
}
